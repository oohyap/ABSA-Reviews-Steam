import matplotlib.pyplot as plt
import pandas as pd

# Ekstrak log dari trainer
log_history = trainer.state.log_history

# Filter log untuk training loss dan validation loss
train_losses = []
val_losses = []
steps = []

for log in log_history:
    if 'loss' in log: # Training loss
        train_losses.append(log['loss'])
        steps.append(log['step'])
    if 'eval_loss' in log: # Validation loss
        val_losses.append(log['eval_loss'])

# Pastikan jumlah elemen sama untuk plotting, atau sesuaikan jika ada perbedaan
# Biasanya eval_loss akan muncul setiap 'eval_strategy', jadi mungkin ada perbedaan jumlah
# Jika jumlahnya berbeda, kita bisa membuat x-axis terpisah atau menginterpolasi

# Untuk mempermudah, kita akan menggunakan 'step' untuk x-axis training loss
# Dan 'epoch' (atau setiap 1 eval_step) untuk validation loss

# Ambil step untuk eval_loss (biasanya pada akhir epoch)
# Asumsi eval_strategy="epoch", jadi eval_loss muncul per epoch
epochs_for_val = [log['epoch'] for log in log_history if 'eval_loss' in log]

plt.figure(figsize=(10, 6))
plt.plot(steps[:len(train_losses)], train_losses, label='Training Loss', marker='o', markersize=4, linestyle='-')
plt.plot(epochs_for_val, val_losses, label='Validation Loss', marker='x', markersize=6, linestyle='--')

