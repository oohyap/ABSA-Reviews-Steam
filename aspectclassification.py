import torch
from transformers import AutoModelForSequenceClassification, TrainingArguments, Trainer
from sklearn.metrics import accuracy_score, precision_recall_fscore_support
import numpy as np

# 1. Mengonversi label 'Aspect' ke ID numerik
# Dapatkan semua label unik dari kolom 'Aspect' di seluruh dataset asli
all_aspect_labels = df['Aspect'].unique()
label_list = sorted(all_aspect_labels) # Urutkan untuk konsistensi

label_to_id = {label: i for i, label in enumerate(label_list)}
id_to_label = {i: label for i, label in enumerate(label_list)}

print(f"Label to ID mapping: {label_to_id}")
print(f"ID to Label mapping: {id_to_label}")

# Ubah label 'Aspect' dari y_aspect_train, y_aspect_val, y_aspect_test menjadi ID numerik
y_train_labels = y_aspect_train.map(label_to_id)
y_val_labels = y_aspect_val.map(label_to_id)
y_test_labels = y_aspect_test.map(label_to_id)

# 2. Buat PyTorch Dataset
class AspectDataset(torch.utils.data.Dataset):
    def __init__(self, encodings, labels):
        self.encodings = encodings
        self.labels = labels

    def __getitem__(self, idx):
        item = {key: torch.tensor(val[idx]) for key, val in self.encodings.items()}
        item['labels'] = torch.tensor(self.labels[idx])
        return item

    def __len__(self):
        return len(self.labels)

train_dataset = AspectDataset(tokenized_train, y_train_labels.values)
val_dataset = AspectDataset(tokenized_val, y_val_labels.values)
test_dataset = AspectDataset(tokenized_test, y_test_labels.values)

# 3. Muat model IndoBERT untuk klasifikasi urutan
model = AutoModelForSequenceClassification.from_pretrained(
    "indobenchmark/indobert-base-p1",
    num_labels=len(label_list),
    id2label=id_to_label,
    label2id=label_to_id,
    ignore_mismatched_sizes=True # Tambahkan baris ini
)

# 4. Definisikan metrik komputasi
def compute_metrics(pred):
    labels = pred.label_ids
    preds = pred.predictions.argmax(-1)
    precision, recall, f1, _ = precision_recall_fscore_support(labels, preds, average='weighted')
    acc = accuracy_score(labels, preds)
    return {
        'accuracy': acc,
        'f1': f1,
        'precision': precision,
        'recall': recall
    }

# 5. Konfigurasi argumen pelatihan
training_args = TrainingArguments(
    output_dir='./results_aspect_classification',
    num_train_epochs=3,
    per_device_train_batch_size=16,
    per_device_eval_batch_size=16,
    warmup_steps=500,
    weight_decay=0.01,
    logging_dir='./logs',
    logging_steps=10,
    eval_strategy="epoch", # Lakukan evaluasi setiap epoch
    save_strategy="epoch",      # Simpan model setiap epoch
    load_best_model_at_end=True, # Ganti load_best_model_as_init_checkpoint menjadi load_best_model_at_end
    metric_for_best_model="f1", # Metrik untuk memilih model terbaik
    greater_is_better=True
)

# 6. Inisialisasi Trainer
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=val_dataset,
    compute_metrics=compute_metrics
)

# 7. Mulai pelatihan
print("Memulai fine-tuning model...")
trainer.train()
print("Fine-tuning selesai!")

