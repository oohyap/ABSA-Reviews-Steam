def predict_aspect(text):
    # Tokenisasi teks input
    inputs = aspect_tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=128).to(device)

    # Lakukan inferensi tanpa menghitung gradien
    with torch.no_grad():
        outputs = aspect_model(**inputs)

    # Ambil index dengan logit tertinggi
    probs = torch.nn.functional.softmax(outputs.logits, dim=-1)
    predicted_class_id = torch.argmax(probs, dim=-1).item()

    # Kembalikan nama label dari mapping
    return label_map[predicted_class_id]

