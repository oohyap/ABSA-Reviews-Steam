import re

def predict_multiple_aspect_sentiment(text):
    results = []
    # Simple splitting based on common conjunctions to identify potential separate clauses
    # This is a heuristic approach to handle multiple aspect/sentiment expressions
    # For more robust Aspect-Based Sentiment Analysis, dedicated libraries or more complex models are typically used.
    sentences = re.split(r'(?i)\b(tapi|dan|namun|tetapi)\b[,.]*', text)
    sentences = [s.strip() for s in sentences if s.strip()]

    # If splitting yields only one segment, treat it as a single review
    if not sentences:
        return []
    elif len(sentences) == 1:
        aspect = predict_aspect(text)
        sentiment = predict_sentiment(text)
        results.append({
            "text_segment": text,
            "aspect": aspect,
            "sentiment": sentiment
        })
    else:
        for segment in sentences:
            if segment:
                aspect = predict_aspect(segment)
                sentiment = predict_sentiment(segment)
                results.append({
                    "text_segment": segment,
                    "aspect": aspect,
                    "sentiment": sentiment
                })
    return results

# Example usage with the previous input, which has two distinct sentiments/aspects
