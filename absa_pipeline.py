# Mapping manual berdasarkan output sebelumnya (LABEL_0=Positif, LABEL_1=Negatif)
sentiment_mapping = {'LABEL_0': 'Positif', 'LABEL_1': 'Negatif'}

def predict_sentiment(text):
    inputs = sentiment_tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=128).to(device)
    with torch.no_grad():
        outputs = sentiment_model(**inputs)
    predicted_class_id = torch.argmax(outputs.logits, dim=-1).item()
    raw_label = sentiment_model.config.id2label[predicted_class_id]
    return sentiment_mapping.get(raw_label, raw_label)

